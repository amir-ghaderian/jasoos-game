// همه کلمات را در یک آرایه قرار می‌دهیم
export const allWords = words.flatMap(
  (category) => category.words
);

// کلید ذخیره سابقه در localStorage
const STORAGE_KEY = "usedWords";

// خواندن سابقه کلمات استفاده‌شده
const readUsedWords = (): string[] => {
  if (typeof window === "undefined") {
    return [];
  }

  try {
    const saved = localStorage.getItem(STORAGE_KEY);

    if (!saved) {
      return [];
    }

    const parsed: unknown = JSON.parse(saved);

    if (!Array.isArray(parsed)) {
      return [];
    }

    return parsed.filter(
      (word): word is string => typeof word === "string"
    );
  } catch {
    return [];
  }
};

// ذخیره سابقه کلمات
const saveUsedWords = (usedWords: string[]): void => {
  if (typeof window === "undefined") {
    return;
  }

  try {
    localStorage.setItem(
      STORAGE_KEY,
      JSON.stringify(usedWords)
    );
  } catch {
    // در صورت محدودیت ذخیره‌سازی، بازی متوقف نمی‌شود.
  }
};

// به‌هم‌زدن ترتیب کلمات به روش Fisher-Yates
const shuffleWords = (items: string[]): string[] => {
  const result = [...items];

  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));

    [result[i], result[j]] = [result[j], result[i]];
  }

  return result;
};

// انتخاب چند کلمه بدون تکرار
export const getRandomWords = (count: number): string[] => {
  // حذف کلمات تکراری احتمالی از مجموعه اصلی
  const pool = [...new Set(allWords)];

  if (
    !Number.isFinite(count) ||
    count <= 0 ||
    pool.length === 0
  ) {
    return [];
  }

  // تعداد درخواستی نباید از تعداد کل کلمات بیشتر باشد
  const safeCount = Math.min(
    Math.floor(count),
    pool.length
  );

  // سابقه فقط برای کلمات موجود در مجموعه فعلی معتبر است
  const poolSet = new Set(pool);

  const usedWords = [
    ...new Set(
      readUsedWords().filter((word) => poolSet.has(word))
    ),
  ];

  const usedSet = new Set(usedWords);

  // کلماتی که در چرخه فعلی هنوز استفاده نشده‌اند
  const availableWords = pool.filter(
    (word) => !usedSet.has(word)
  );

  let selectedWords: string[];
  let updatedUsedWords: string[];

  if (availableWords.length >= safeCount) {
    // به‌اندازه کافی کلمه استفاده‌نشده داریم
    selectedWords = shuffleWords(availableWords).slice(
      0,
      safeCount
    );

    updatedUsedWords = [
      ...usedWords,
      ...selectedWords,
    ];
  } else {
    // کلمات باقی‌مانده را انتخاب می‌کنیم
    selectedWords = shuffleWords(availableWords);

    const selectedSet = new Set(selectedWords);
    const remainingCount =
      safeCount - selectedWords.length;

    // چرخه جدید فقط برای تکمیل تعداد درخواستی شروع می‌شود
    const restartCandidates = pool.filter(
      (word) => !selectedSet.has(word)
    );

    const additionalWords = shuffleWords(
      restartCandidates
    ).slice(0, remainingCount);

    selectedWords.push(...additionalWords);

    // شروع چرخه جدید؛ انتخاب فعلی در ابتدای سابقه قرار می‌گیرد
    updatedUsedWords = [...selectedWords];
  }

  saveUsedWords(updatedUsedWords);

  return selectedWords;
};

// انتخاب یک کلمه با همان سیستم سابقه
export const getRandomWord = (): string => {
  return getRandomWords(1)[0] ?? "";
};

// پاک کردن سابقه کلمات استفاده‌شده
export const resetUsedWords = (): void => {
  if (typeof window === "undefined") {
    return;
  }

  try {
    localStorage.removeItem(STORAGE_KEY);
  } catch {
    // اگر پاک کردن سابقه ممکن نباشد، خطای برنامه‌ای ایجاد نمی‌کنیم.
  }
};